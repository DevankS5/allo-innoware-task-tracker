/* Employee completion and manager acknowledgement (docs/02-LLD.md sections 12 and 14).
 * Identity is never invented: an unreadable actor is recorded as UNVERIFIED with a blank email. */

/** Event path: only e.user is trusted (getActiveUser() in an installable trigger can be the trigger owner). */
function resolveActor(e, fallbackEmail) {
  let email = '';
  try {
    if (e) { if (e.user && e.user.getEmail) email = e.user.getEmail(); }
    else email = Session.getActiveUser().getEmail();
  } catch (x) { /* identity unavailable in this context */ }
  if (email) return { email, source: e ? SOURCE.EVENT_USER : SOURCE.AUTHENTICATED_UI };
  if (cfgBool('ROW_PROTECTION_ACTIVE') && fallbackEmail) return { email: fallbackEmail, source: SOURCE.FALLBACK };
  return { email: '', source: SOURCE.UNVERIFIED };
}

const URL_RE = /^https?:\/\/\S+$/i;

/** '' when the proof satisfies the cycle's contract, else a message for the employee. */
function validateProof(c, task) {
  const proof = str(c.Employee_Proof), url = str(c.Evidence_URL), note = str(c.Employee_Notes);
  if (url && !URL_RE.test(url)) return 'Evidence_URL must be a full http(s) link.';
  if (task && !isBlank(task.Proof_Required) && !toBool(task.Proof_Required)) return '';
  switch (c.Required_Proof_Type) {
    case 'TICKET_ID': return proof ? '' : 'Enter the portal Ticket ID in Employee_Proof before submitting.';
    case 'WHATSAPP_ATTESTATION':
      if (!proof) return 'Enter a short reference of the WhatsApp post (e.g. "Posted 16:42 - daily operations summary").';
      return cfgBool('WHATSAPP_EVIDENCE_URL_REQUIRED') && !url ? 'This task also requires an Evidence_URL (screenshot link).' : '';
    case 'URL_OR_NOTE': return proof || url || note ? '' : 'Enter a proof reference, an evidence link or a note.';
    default: return '';
  }
}

function processCompletion(cycleId, actorCtx) { resetCaches(); return withLock(() => processCompletion_(cycleId, actorCtx)); }

function processCompletion_(cycleId, a) {
  const now = getEffectiveNow(), c = findCycle(cycleId);
  const reject = (msg, why) => {
    if (c) tbl(CYCLES).update(c.__row, { Submit_Complete: false });
    audit('COMPLETION_SUBMITTED', { cycleId, taskId: c && c.Task_ID, actor: a.email, source: a.source, details: { accepted: false, reason: why } });
    return { accepted: false, message: msg, cycleId };
  };
  if (!c) return { accepted: false, message: 'Cycle not found', cycleId };
  if (c.Status === STATUS.COMPLETED) {
    if (!toBool(c.Submit_Complete)) tbl(CYCLES).update(c.__row, { Submit_Complete: true });
    return { accepted: true, noop: true, message: 'Already completed; no change.', cycleId };
  }
  if (c.Status === STATUS.CANCELLED) return reject('This cycle was cancelled.', 'cancelled');
  if (a.email && lc(a.email) !== lc(c.Assigned_To_Email) && !isAdminEmail(a.email))
    return reject('Only ' + c.Assigned_To_Email + ' (or an admin) can complete this task.', 'not assignee');
  const task = taskById(c.Task_ID), bad = validateProof(c, task);
  if (bad) return reject(bad, 'proof');

  tbl(CYCLES).update(c.__row, {
    Status: STATUS.COMPLETED, Submit_Complete: true, Completed_At: now, Completed_By_Email: a.email, Completed_By_Source: a.source,
    Updated_At: now, Resolved_After_Escalation_At: isBlank(c.Leadership_Escalated_At) ? '' : now,
  });
  tbl(SHEETS.ALERT_LOG).rows().filter(x => x.Cycle_ID === cycleId && (x.Status === 'FAILED' || x.Status === 'PENDING'))
    .forEach(x => tbl(SHEETS.ALERT_LOG).update(x.__row, { Status: 'CANCELLED' }));
  audit('CYCLE_COMPLETED', { cycleId, taskId: c.Task_ID, actor: a.email, source: a.source, from: c.Status, to: STATUS.COMPLETED,
    details: { proof: str(c.Employee_Proof).slice(0, 200), evidence: str(c.Evidence_URL), late: now > toDate(c.Due_At), afterEscalation: !isBlank(c.Leadership_Escalated_At) } });

  let nextCycleId = '';
  if (task && toBool(task.Is_Active) && task.Frequency_Type === 'INTERVAL') { // daily tasks are generated by the dispatcher
    const nx = intervalNextDue(task, c, now), created = createCycle(task, nx.dueAt, keyInterval(task.Task_ID, nx.dueAt), now);
    if (created) nextCycleId = created.Cycle_ID;
    if (nx.skipped) audit('RECONCILIATION_REPAIRED', { cycleId, taskId: task.Task_ID, details: { note: 'fixed cadence skipped ' + nx.skipped + ' slot(s)' } });
  }
  return { accepted: true, message: 'Completed.', cycleId, nextCycleId };
}

function processManagerAcknowledgement(cycleId, actorCtx) { resetCaches(); return withLock(() => processManagerAck_(cycleId, actorCtx)); }

function processManagerAck_(cycleId, a) {
  const now = getEffectiveNow(), c = findCycle(cycleId);
  const reject = msg => { if (c) tbl(CYCLES).update(c.__row, { Manager_Acknowledged: false }); return { accepted: false, message: msg, cycleId }; };
  if (!c) return { accepted: false, message: 'Cycle not found', cycleId };
  if (!isBlank(c.Manager_Ack_At)) {
    if (!toBool(c.Manager_Acknowledged)) tbl(CYCLES).update(c.__row, { Manager_Acknowledged: true });
    return { accepted: true, noop: true, message: 'Already acknowledged; no change.', cycleId };
  }
  if (c.Status !== STATUS.DUE && c.Status !== STATUS.OVERDUE) return reject('Only DUE or OVERDUE cycles can be acknowledged (this one is ' + c.Status + ').');
  const m = memberByEmail(a.email);
  if (a.email && lc(a.email) !== lc(c.Manager_Email) && !(m && (m.Role === 'ADMIN' || toBool(m.Can_Acknowledge))))
    return reject('Only ' + c.Manager_Email + ' (or an approved manager/admin) can acknowledge this task.');
  if (!str(c.Manager_Notes)) return reject('Enter a short action note in Manager_Notes before acknowledging.');
  tbl(CYCLES).update(c.__row, { Manager_Acknowledged: true, Manager_Ack_At: now, Manager_Ack_By_Email: a.email, Manager_Ack_Source: a.source, Updated_At: now });
  audit('MANAGER_ACKNOWLEDGED', { cycleId, taskId: c.Task_ID, actor: a.email, source: a.source, from: c.Status, to: c.Status, details: { notes: str(c.Manager_Notes).slice(0, 300) } });
  return { accepted: true, message: 'Acknowledged. The task stays open until the employee completes it.', cycleId };
}
